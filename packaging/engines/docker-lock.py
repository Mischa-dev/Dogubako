#!/usr/bin/env python3
"""Pin the homelab image's engines: resolve the Debian packages named in
engines.toml against the snapshot in [docker] and write their exact versions.

    python3 -I packaging/engines/docker-lock.py     # needs Docker; writes docker-packages*.txt

The Dockerfile installs exactly these `package=version` lines (the whole
dependency closure), from deb.debian.org when it still has that version and
from the snapshot otherwise, so an image build always gets the engine set that
was tested.
Bump = change [docker].snapshot, re-run this, rebuild, run the image's
`dogubako deps`, commit.
"""

from __future__ import annotations

import re
import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "engines.toml"
# Base packages the image needs besides the engines.
BASE = ["ca-certificates", "tini", "fonts-dejavu-core"]


def resolve(image: str, snapshot: str, suite: str, packages: list[str]) -> dict[str, str]:
    script = f"""
set -e
cat > /etc/apt/sources.list.d/debian.sources <<EOF
Types: deb
URIs: http://snapshot.debian.org/archive/debian/{snapshot}
Suites: {suite} {suite}-updates
Components: main
Check-Valid-Until: no

Types: deb
URIs: http://snapshot.debian.org/archive/debian-security/{snapshot}
Suites: {suite}-security
Components: main
Check-Valid-Until: no
EOF
for i in 1 2 3 4 5; do apt-get -qq -o Acquire::Retries=5 update && break; sleep $((i*10)); done
apt-get install -s --no-install-recommends {' '.join(packages)}
"""
    out = subprocess.run(
        ["docker", "run", "--rm", image, "sh", "-c", script],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    versions = {}
    for line in out.splitlines():
        m = re.match(r"Inst (\S+) \((\S+) ", line)
        if m:
            versions[m.group(1)] = m.group(2)
    missing = [p for p in packages if p not in versions]
    if missing:
        raise SystemExit(f"not resolvable in snapshot {snapshot}: {', '.join(missing)}")
    # The whole closure, not just the named packages: with every version
    # fixed, the image is identical whichever mirror serves the files.
    return versions


def write(path: Path, header: str, pins: dict[str, str]) -> None:
    body = "".join(f"{p}={v}\n" for p, v in sorted(pins.items()))
    path.write_text(header + body)
    print(f"wrote {path.name} ({len(pins)} packages)", file=sys.stderr)


def main() -> None:
    m = tomllib.loads(MANIFEST.read_text())
    d = m["docker"]
    image = f"debian:{d['debian_suite']}-slim@{d['base_digest']}"
    core, optional = list(BASE), []
    for e in m["engine"].values():
        if e["tier"] == "dropped":
            continue
        (optional if e.get("docker_optional") else core).extend(e.get("debian", []))
    header = (
        "# Generated by packaging/engines/docker-lock.py from engines.toml; do not edit.\n"
        f"# snapshot {d['snapshot']} ({d['debian_suite']})\n"
    )
    write(HERE / "docker-packages.txt", header, resolve(image, d["snapshot"], d["debian_suite"], core))
    if optional:
        write(
            HERE / "docker-packages-office.txt",
            header,
            resolve(image, d["snapshot"], d["debian_suite"], optional),
        )


if __name__ == "__main__":
    main()
