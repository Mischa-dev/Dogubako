#!/usr/bin/env python3
"""Pin the homelab image's engines: resolve the Debian packages named in
engines.toml against the snapshot in [docker] and write their exact versions,
once per architecture the image is built for.

    python3 -I packaging/engines/docker-lock.py                # writes docker-packages*-<arch>.txt for every arch
    python3 -I packaging/engines/docker-lock.py --arch arm64   # just one
    python3 -I packaging/engines/docker-lock.py --check --arch "$(dpkg --print-architecture)"

Needs Docker or Podman, and for an architecture other than the machine's own,
QEMU emulation (binfmt). The Dockerfile installs exactly the `package=version`
lines for its architecture (the whole dependency closure), from deb.debian.org
when it still has that version and from the snapshot otherwise, so an image
build always gets the engine set that was tested. Each architecture has its own
list because the closure differs (libvpl2 is amd64-only) and so can binNMU
versions.
Bump = change [docker].snapshot, re-run this, rebuild, run the image's
`dogubako deps`, commit.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "engines.toml"
# Base packages the image needs besides the engines.
BASE = ["ca-certificates", "tini", "fonts-dejavu-core"]
# Debian architectures the image is built for (dpkg --print-architecture).
ARCHES = ["amd64", "arm64"]


def container_runtime() -> str:
    for rt in ("docker", "podman"):
        if shutil.which(rt):
            return rt
    raise SystemExit("needs docker or podman")


def resolve(runtime: str, image: str, arch: str, snapshot: str, suite: str, packages: list[str]) -> dict[str, str]:
    script = f"""
set -e
cat > /etc/apt/sources.list.d/debian.sources <<EOF
Types: deb
URIs: http://snapshot.debian.org/archive/debian/{snapshot}
Suites: {suite} {suite}-updates
Components: main
Check-Valid-Until: no

Types: deb
URIs: http://snapshot.debian.org/archive/debian-security/{snapshot}
Suites: {suite}-security
Components: main
Check-Valid-Until: no
EOF
for i in 1 2 3 4 5; do apt-get -qq -o Acquire::Retries=5 update && break; sleep $((i*10)); done
test "$(dpkg --print-architecture)" = {arch}
apt-get install -s --no-install-recommends {' '.join(packages)}
"""
    out = subprocess.run(
        [runtime, "run", "--rm", "--platform", f"linux/{arch}", image, "sh", "-c", script],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    versions = {}
    for line in out.splitlines():
        m = re.match(r"Inst (\S+) \((\S+) ", line)
        if m:
            versions[m.group(1)] = m.group(2)
    missing = [p for p in packages if p not in versions]
    if missing:
        raise SystemExit(f"not resolvable in snapshot {snapshot} for {arch}: {', '.join(missing)}")
    # The whole closure, not just the named packages: with every version
    # fixed, the image is identical whichever mirror serves the files.
    return versions


def render(header: str, pins: dict[str, str]) -> str:
    return header + "".join(f"{p}={v}\n" for p, v in sorted(pins.items()))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--arch", action="append", choices=ARCHES, help="only this architecture (repeatable; default: all)")
    ap.add_argument("--check", action="store_true", help="only verify the lists match engines.toml and the snapshot")
    args = ap.parse_args()
    m = tomllib.loads(MANIFEST.read_text())
    d = m["docker"]
    image = f"debian:{d['debian_suite']}-slim@{d['base_digest']}"
    core, optional = list(BASE), []
    for e in m["engine"].values():
        if e["tier"] == "dropped":
            continue
        (optional if e.get("docker_optional") else core).extend(e.get("debian", []))
    runtime = container_runtime()
    stale = []
    for arch in args.arch or ARCHES:
        header = (
            "# Generated by packaging/engines/docker-lock.py from engines.toml; do not edit.\n"
            f"# snapshot {d['snapshot']} ({d['debian_suite']}, {arch})\n"
        )
        lists = {f"docker-packages-{arch}.txt": core}
        if optional:
            lists[f"docker-packages-office-{arch}.txt"] = optional
        for name, packages in lists.items():
            text = render(header, resolve(runtime, image, arch, d["snapshot"], d["debian_suite"], packages))
            path = HERE / name
            if args.check:
                if not path.exists() or path.read_text() != text:
                    stale.append(name)
                continue
            path.write_text(text)
            print(f"wrote {name} ({text.count(chr(10)) - 2} packages)", file=sys.stderr)
    for name in stale:
        print(f"stale: {name} (re-run docker-lock.py)", file=sys.stderr)
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
