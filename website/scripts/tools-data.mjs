#!/usr/bin/env node
// Rewrites assets/js/tools-data.js (the tool list the home finder and the tools page search)
// from the real tool catalog, then you run build-tools-page.mjs to refresh the no-JS list.
//
//   dogubako tools list --json > /tmp/tools.json          # or the docs site's public/tools.json
//   node website/scripts/tools-data.mjs /tmp/tools.json
//   node website/scripts/build-tools-page.mjs
//
// Shape (kept small on purpose): DGB_CATS = [[id, label, lucide icon], …] in display order;
// DGB_TOOLS = [[category index, name, id, description, "keywords joined by spaces"], …].

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CATS = [
  ['image', 'Images', 'image'], ['video', 'Video', 'clapperboard'], ['audio', 'Audio', 'audio-lines'],
  ['speech', 'Speech & Voice', 'mic'], ['pdf', 'PDF & Documents', 'file-text'], ['files', 'Files', 'folder-archive'],
  ['text', 'Text', 'type'], ['dev', 'Developer', 'code-xml'], ['data', 'Data', 'sheet'],
  ['network', 'Network & Web', 'globe'], ['design', 'Design', 'palette'], ['system', 'System', 'cpu'],
];

const src = process.argv[2];
if (!src) { console.error('usage: tools-data.mjs <tools.json>'); process.exit(2); }
const raw = JSON.parse(readFileSync(src, 'utf8'));
const list = Array.isArray(raw) ? raw : raw.tools;
const index = new Map(CATS.map((c, i) => [c[0], i]));
const unknown = [...new Set(list.map((t) => t.category).filter((c) => !index.has(c)))];
if (unknown.length) throw new Error(`unknown categories (add them to CATS): ${unknown.join(', ')}`);

const tools = list
  .map((t, order) => ({ t, order }))
  .sort((a, b) => index.get(a.t.category) - index.get(b.t.category) || a.order - b.order)
  .map(({ t }) => [index.get(t.category), t.name, t.id, t.description, (t.keywords || []).join(' ')]);

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets/js/tools-data.js');
writeFileSync(out,
  `/* Generated by scripts/tools-data.mjs from the tool catalog (dogubako tools list --json). ${tools.length} tools. */\n` +
  `window.DGB_CATS=${JSON.stringify(CATS)};\n` +
  `window.DGB_TOOLS=${JSON.stringify(tools)};\n`);
console.log(`wrote ${tools.length} tools in ${CATS.length} categories to ${out}`);
